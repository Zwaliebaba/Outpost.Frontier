/// `InvSqrt(x)`: an estimate of `1 / sqrt(x)` from the table, refined by
/// two Newton steps that each round to `f32`. The sign of `x` is ignored
/// when the estimate is formed, so negative inputs grow toward infinity;
/// zero gives a large finite value.
#[must_use]
pub fn inv_sqrt(x: f32) -> f32 {
    let bits = x.to_bits();
    let exponent = (bits >> 23) & 0xFF;
    let index = ((bits >> 14) & 0x3FF) as usize;
    let mut guess = (0x5F00_0000 - (exponent << 22)) & 0xFF80_0000;
    guess |= u32::from(INV_SQRT_TABLE[index]) << 15;
    let mut y = f32::from_bits(guess);
    // `Y = (3.0f - Y * Y * X) * Y * 0.5f;` twice, rounded at each
    // assignment.
    for _ in 0..2 {
        y = round((3.0 - ext(y) * ext(y) * ext(x)) * ext(y) * 0.5);
    }
    y
}

/// `Sqrt(x)`: `InvSqrt(x) * x`.
#[must_use]
pub fn sqrt(x: f32) -> f32 {
    round(ext(inv_sqrt(x)) * ext(x))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `BuildInvSqrtTable` as the reference runs it on the 53-bit stack.
    fn build_table() -> [u8; 0x400] {
        let mut table = [0u8; 0x400];
        for (index, entry) in (0u32..).zip(table.iter_mut()) {
            let x = f32::from_bits((index | 0xFC00) << 14);
            let recip = round(1.0 / ext(x).sqrt()).to_bits();
            *entry = ((recip + 0x2000) >> 15).to_le_bytes()[0];
        }
        table[0x200] = 0xFF;
        table
    }

    #[test]
    fn table_matches_the_load_time_computation() {
        assert_eq!(build_table(), INV_SQRT_TABLE);
    }

    #[test]
    fn known_values() {
        assert_eq!(inv_sqrt(4.0), 0.5);
        assert_eq!(inv_sqrt(1.0), 1.0);
        assert_eq!(sqrt(16.0), 4.0);
        assert_eq!(sqrt(0.0), 0.0);
        assert!(inv_sqrt(0.0).is_finite());
        assert!((inv_sqrt(2.0) - core::f32::consts::FRAC_1_SQRT_2).abs() < 1e-6);
        assert!(inv_sqrt(f32::NAN).is_nan());
        // The first Newton step overflows to -inf, the second to +inf.
        assert_eq!(inv_sqrt(f32::INFINITY), f32::INFINITY);
    }

    #[test]
    fn close_to_the_true_reciprocal_root() {
        for bits in (0x0080_0000u32..0x7F00_0000).step_by(0x0001_0003) {
            let x = f32::from_bits(bits);
            let want = 1.0 / ext(x).sqrt();
            let got = ext(inv_sqrt(x));
            assert!(((got - want) / want).abs() < 4e-7, "{x}: {got} vs {want}");
        }
    }
}
